// THE METAL'S SPECULAR LOBE, INTEGRATED (METAL-BOUNCE-1, ENGINE-UPGRADE-U5 stage 5).
//
// What a surface's specular lobe reflects of the light reaching it from one direction is its
// DIRECTIONAL ALBEDO, and for HlmsPbs's lobe (BRDF_Default, 200.BRDFs_piece_ps.any: GGX D, the
// height-correlated Smith GGX visibility, Schlick's Fresnel on V.H, alpha = perceptual roughness
// squared) that is linear in F0:
//
//     E( v, r ) = F0 x A( v, r ) + B( v, r ),
//     A = integral over l of ( 1 - Fc ) D Vis cos_l,   B = integral of Fc D Vis cos_l,   Fc = ( 1 - V.H )^5
//
// (by reciprocity the same function of the light's cosine as of the view's). What it reflects of a
// UNIFORM incoming hemisphere is the HEMISPHERICAL mean, A-bar( r ) = 2 x integral of A( mu, r ) mu dmu
// and B-bar likewise. The voxel store re-emits the metal's share of the lobe with them
// (LightInjection: a lamp at cosine mu re-emits mu x ( F0 A( mu, r ) + w B( mu, r ) ); the bounce:
// F0 A-bar( r ) + w B-bar( r ) of what it gathers), and a ray's hit shades a metal with the same
// directional term (jah_rq_hit_direct.glsl): a white rough metal re-emits by its lobe integral,
// where a diffuse-only store made it re-emit 0.
//
// A TABLE, NOT A FIT. A polynomial in ( 1 - v, r ) - the diffuse lobe's form (JahDiffuseAlbedo) - was
// tried and left 1.4 - 2.5 % worst at v >= 0.2 with 17 - 20 terms: the lobe's Fresnel shoulder at low
// roughness is not polynomial. Bilinear on this 32 x 32 grid is within 0.22 % of the integral at
// v >= 0.2 and 0.07 % times the cosine everywhere (measured at 529 off-grid points). Ogre's own DFG
// table (brtfLutDfg.dds, the LTC matrix's third slice) holds the same two channels but reads up to
// 2.2 % BELOW this integral at normal incidence (0.616 against 0.638 at r = 0.74: another visibility
// term or fewer samples), and HlmsPbs binds it only beside an area light.
//
// GENERATED, the integral by the sampler stated here: the half vector drawn by D( h ) cos( h ),
// 512 x 512 stratified (phi over a half circle - the lobe is symmetric), alpha floored at 1e-3 and v
// at 1e-3; the hemispherical rows from 128 cosines at 384 x 384. The suites state the same integral
// independently (tests/support/enginetesthelpers.h, ggxSpecularAlbedo) and gi.metal_bounce asserts the
// store against it - the table is never the test's reference.
//
// LAYOUT: directional entry ( i, j ) at [ 2 ( 32 j + i ) ] (A) and [ 2 ( 32 j + i ) + 1 ] (B), at
// v = i / 31, r = j / 31; hemispherical entry j at [ 2 j ] (A-bar) and [ 2 j + 1 ] (B-bar), r = j / 31.
// The GPU reads both through JahSpecularAlbedo_piece_all.any (the Photon jobs' constant buffer,
// PhotonVoxelLighting) and the ray tier's hit table (OgreRayQuery: the same floats, appended).
